/** Keywords to suggest for `engine` (core + dialect extras; CQL stands alone). */
export function keywordsFor(engine: Engine | undefined): string[] {
  if (engine === "cassandra") return CQL_KEYWORDS;
  if (!engine) return CORE_KEYWORDS;
  return [...CORE_KEYWORDS, ...(KEYWORD_EXTRAS[engine] ?? [])];
}

/** Functions to suggest for `engine` (core + dialect extras; CQL stands alone). */
export function functionsFor(engine: Engine | undefined): string[] {
  if (engine === "cassandra") return CQL_FUNCTIONS;
  if (!engine) return CORE_FUNCTIONS;
  return [...CORE_FUNCTIONS, ...(FUNCTION_EXTRAS[engine] ?? [])];
}

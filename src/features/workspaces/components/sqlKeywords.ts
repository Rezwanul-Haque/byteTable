// Per-dialect keyword / function vocabularies for the autocomplete suggester
// (sqlSuggest.ts). Split out of sqlSuggest so the ranking core stays small and
// the word lists can grow per engine without touching the algorithm.
//
// SHAPE: a shared ANSI CORE that every SQL engine understands, plus an EXTRAS
// table keyed by Engine holding only that dialect's own syntax. `keywordsFor`
// concatenates core + extras — EXCEPT for Cassandra, whose CQL is a subset with
// its own spelling (no joins, no subqueries), so it REPLACES the core outright
// rather than adding to it. Suggesting `RIGHT JOIN` in a CQL editor is worse
// than suggesting nothing.
//
// ORDER IS THE RANKING. sqlSuggest returns matches in array order (nothing
// re-sorts downstream), so the most-used words come first within each list and
// core words outrank dialect extras on an equal prefix.
//
// CASE: entries are inserted verbatim. SQL words are upper-case (house style,
// matching formatSql); ClickHouse's camelCase functions are NOT uppercased —
// `toDateTime` is a different identifier from `TODATETIME` there.

